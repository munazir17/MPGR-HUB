#!/usr/bin/env node
// Generates lib/executor/mpgr-executor-abi.ts from the compiled contract so the
// TypeScript ABI can never drift from contracts/executor/MPGRExecutor.sol.
//
//   node script/gen-executor-abi.mjs          # (re)write the file
//   node script/gen-executor-abi.mjs --check  # CI: fail if the file is stale
//
// Requires `forge` on PATH and the Solidity deps in .forge-deps (see CI).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "lib/executor/mpgr-executor-abi.ts");

const abiJson = execFileSync(
  "forge",
  ["inspect", "contracts/executor/MPGRExecutor.sol:MPGRExecutor", "abi", "--json"],
  { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);
const abi = JSON.parse(abiJson);
// Stable ordering: type, then name — so regeneration is deterministic.
abi.sort((a, b) => `${a.type}:${a.name ?? ""}`.localeCompare(`${b.type}:${b.name ?? ""}`));

const content = `// AUTO-GENERATED by script/gen-executor-abi.mjs from
// contracts/executor/MPGRExecutor.sol — DO NOT EDIT BY HAND.
// CI (contracts job) runs \`node script/gen-executor-abi.mjs --check\`.

export const MPGR_EXECUTOR_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file is stale
  }
  if (current !== content) {
    console.error("lib/executor/mpgr-executor-abi.ts is stale. Run: node script/gen-executor-abi.mjs");
    process.exit(1);
  }
  console.log("executor ABI is up to date");
} else {
  writeFileSync(target, content);
  console.log(`wrote ${target} (${abi.length} entries)`);
}
