// Minimal ABIs actually used for tokenized-stock research.
//
// IB20 / ERC-20 reads come from Base B20 docs. Only functions we call
// are listed. The oracle registry ABI is not published in that guide
// with a callable signature, so this module does NOT guess one — the
// token's own `multiplier()` plus Chainlink `latestRoundData()` cover
// the documented price formula:
//   Token Price = Underlying Equity Market Price × Multiplier
// Coinbase Chainlink equity feeds already publish that total-return
// value, so research code must not multiply the feed by multiplier again.

